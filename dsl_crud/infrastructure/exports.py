"""Files the app derives from the items and writes to paths set in Settings
(the .bib file, the portfolio page, the published site): one runner for all
of them, debounced after writes, at startup and periodically."""

import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from dsl_crud.infrastructure import config
from dsl_crud.infrastructure.errors import ValidationError

DEBOUNCE = 5  # seconds after the last change
INTERVAL = 15 * 60  # full resync, picks up edits made outside the app
# in a folder export's folder: its marker, then every file it wrote there
MANIFEST = ".dsl-crud-manifest"


@dataclass(frozen=True)
class Export:
    # its config key and settings field
    key: str
    # ignored by a folder export
    suffix: str
    # appended to a directory given as path; None for a folder export
    default_name: str | None
    # what a file this export wrote starts with (a folder export: its manifest);
    # any other file is never overwritten
    marker: str
    # the file's text; a folder export's files instead, by path relative to the folder
    render: Callable[[], str | dict[str, bytes]]
    # files written beside it: path relative to its folder -> bytes, all inside
    # `asset_dir`, which the export owns (files there it didn't write this time are deleted)
    assets: Callable[[], dict[str, bytes]] | None = None
    asset_dir: str | None = None
    # the configured path is a folder, which it shares: see _write_folder
    folder: bool = False


EXPORTS: dict[str, Export] = {}

# key -> path -> error message, or None if the last sync succeeded
status: dict[str, dict[str, str | None]] = {}
_lock = threading.Lock()
_timer: threading.Timer | None = None


def register(export: Export) -> None:
    EXPORTS[export.key] = export


def paths(key: str) -> list[dict]:
    """The export's paths, each with its last result."""
    return [{"path": p, "error": status.get(key, {}).get(p)} for p in config.get_export_paths(key)]


def set_paths(key: str, value) -> list[str]:
    if key not in EXPORTS:
        raise ValidationError(f"unknown export '{key}'")
    return config.set_export_paths(key, value, EXPORTS[key].default_name)


def _write(export: Export, path: str, text: str) -> None:
    p = Path(path)
    if not p.is_absolute():
        raise ValueError("not an absolute path")
    if p.suffix != export.suffix:
        raise ValueError(f"must end in {export.suffix}")
    if not p.parent.is_dir():
        raise ValueError(f"{p.parent} does not exist")
    try:
        current = p.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if current == text:
        return
    if current and not current.startswith(export.marker):
        raise ValueError("file exists and was not generated by this app")
    _replace(p, text.encode())


def _replace(p: Path, data: bytes) -> None:
    tmp = p.with_name(f".{p.name}.tmp")
    tmp.write_bytes(data)
    tmp.replace(p)


def _write_assets(export: Export, path: str, assets: dict[str, bytes]) -> None:
    """The assets beside `path`, written after the file itself (its marker check
    vouches for the folder); those in asset_dir no longer among them are deleted."""
    base = Path(path).parent
    folder = base / export.asset_dir
    folder.mkdir(exist_ok=True)
    for rel, data in assets.items():
        p = base / rel
        if p.parent != folder:
            raise ValueError(f"asset {rel} outside {export.asset_dir}/")
        if not (p.is_file() and p.read_bytes() == data):
            _replace(p, data)
    for p in folder.iterdir():
        if p.is_file() and p.relative_to(base).as_posix() not in assets:
            p.unlink()


def _write_folder(export: Export, path: str, files: dict[str, bytes]) -> None:
    """The files into the folder at `path`. It owns only the files its manifest
    lists (.git, a CNAME or another export's files stay): a file there that it
    didn't write is never overwritten, and of its own, those it no longer
    produces are deleted, with the folders that leaves empty."""
    root = Path(path)
    if not root.is_absolute():
        raise ValueError("not an absolute path")
    if not root.is_dir():
        raise ValueError(f"{root} is not a folder")
    manifest = root / MANIFEST
    previous: set[str] = set()
    if manifest.exists():
        lines = manifest.read_text(encoding="utf-8").splitlines()
        if not lines or lines[0] != export.marker:
            raise ValueError(f"{MANIFEST} was not written by this export")
        previous = set(lines[1:])
    for rel in files:
        parts = Path(rel).parts
        if Path(rel).is_absolute() or ".." in parts or rel == MANIFEST:
            raise ValueError(f"invalid path {rel}")
        if rel not in previous and (root / rel).exists():
            raise ValueError(f"{rel} exists and was not generated by this app")

    def record(rels) -> None:
        text = "\n".join([export.marker, *sorted(rels)]) + "\n"
        if not (manifest.exists() and manifest.read_text(encoding="utf-8") == text):
            _replace(manifest, text.encode())

    # listed before they're written, so an interrupted run still owns them
    record(previous | files.keys())
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if not (p.is_file() and p.read_bytes() == data):
            _replace(p, data)
    for rel in previous - files.keys():
        p = root / rel
        if p.is_file():
            p.unlink()
        for parent in p.parents:
            if parent == root or not parent.is_dir() or any(parent.iterdir()):
                break
            parent.rmdir()
    record(files.keys())


def _sync(export: Export) -> dict[str, str | None]:
    targets = config.get_export_paths(export.key)
    if not targets:
        return {}
    try:
        text = export.render()
        assets = export.assets() if export.assets else None
    except Exception as e:  # noqa: BLE001 - report instead of crashing the thread
        return {p: str(e) for p in targets}
    result = {}
    for p in targets:
        try:
            if export.folder:
                _write_folder(export, p, text)
                result[p] = None
                continue
            _write(export, p, text)
            if assets is not None:
                _write_assets(export, p, assets)
            result[p] = None
        except (OSError, ValueError) as e:
            result[p] = str(e)
    return result


def sync(key: str | None = None) -> None:
    """Writes the configured files of `key` (all exports when None). Unchanged files are not touched."""
    with _lock:
        for export in EXPORTS.values():
            if key in (None, export.key):
                status[export.key] = _sync(export)


def schedule() -> None:
    """Debounced sync: runs DEBOUNCE seconds after the last call."""
    global _timer
    if _timer:
        _timer.cancel()
    _timer = threading.Timer(DEBOUNCE, sync)
    _timer.daemon = True
    _timer.start()


def start() -> None:
    """Sync now, then periodically in a daemon thread."""
    def loop():
        while True:
            sync()
            time.sleep(INTERVAL)

    threading.Thread(target=loop, daemon=True).start()
