"""The portfolio page: the one note tagged `portfolio`, its body rendered as
Markdown into the Jinja template it names in a `media` clause, and exported
as HTML to the paths set in Settings. The notes tagged `card` are rendered as
A4 collages (collage.py), written beside the page in `cards/`."""

import re
import threading

import jinja2
from markupsafe import Markup

from dsl_crud.core import documents as views
from dsl_crud.core import dsl, file_kinds, inline_refs
from dsl_crud.features.portfolio import collage
from dsl_crud.infrastructure import exports, items as store, markdown, media as files

TAG = "portfolio"
CARD_TAG = "card"
CARDS_DIR = "cards"
MARKER = "<!-- generated by dsl-crud, edits will be overwritten -->"

_env = jinja2.Environment(autoescape=True)
# a page's requests may overlap; only one of them creates the note
_lock = threading.Lock()


def _note() -> str | None:
    """The tagged note's file; None when there is none, an error when there are several."""
    names = sorted(n for n, e in store._INDEX.refresh().items() if TAG in e.tags)
    if len(names) > 1:
        raise store.ValidationError(f"several notes are tagged {TAG}: {', '.join(names)}")
    return names[0] if names else None


def _template(item: dict) -> str | None:
    return next((f for f in item["files"] if file_kinds.kind(f) is file_kinds.JINJA), None)


def ensure() -> dict:
    """The portfolio note and its template, created when missing; calling it again changes nothing."""
    with _lock:
        name = _note() or store.create({"text": f"Portfolio\n\ntags {TAG}\n"})["file"]
        template = _template(store.get(name))
        if template is None:
            template = f"{files.FILES_DIR}/{name.removesuffix('.txt')}.html.j2"
            try:
                files.path(template)
            except store.NotFound:
                files.write_text(template, file_kinds.JINJA.default)
            files.add(name, template)
        return {"note": store.get_payload(name), "template": template, "cards": collage.available()}


def _card_names() -> list[str]:
    entries = store._INDEX.refresh()
    names = [n for n, e in entries.items() if CARD_TAG in e.tags]
    return sorted(names, key=lambda n: (entries[n].heading.lower(), n))


def cards() -> list[dict]:
    """Every note tagged `card`, by heading, as the API sends it."""
    entries = store._INDEX.refresh()
    return [store._note(n, entries) for n in _card_names()]


def _card_paths(name: str) -> tuple[str, str]:
    stem = name.removesuffix(".txt")
    return f"{CARDS_DIR}/{stem}.webp", f"{CARDS_DIR}/{stem}-thumb.webp"


def _card(name: str, heading: str) -> dict:
    """What the template gets for a card: `image` and `thumb` relative to the page."""
    image, thumb = _card_paths(name)
    return {"file": name, "title": re.sub(r"^#+\s*", "", heading), "image": image, "thumb": thumb}


def _plain(text: str) -> str:
    """`[[target|label]]` as its label, `[[target]]` as its target (a collage has no links); never math."""
    return inline_refs.substitute(text, lambda r: (r.label or r.target).replace("$", "\\$"))


def _card_images(session: collage.Session, name: str) -> tuple[bytes, bytes]:
    doc = dsl.parse(store.SCHEMA, store.get(name)["text"])
    title = "\n".join(re.sub(r"^#+\s*", "", line) for line in _plain("\n".join(doc.body)).splitlines())
    images = [store._dir() / f for f in views.files(doc) if file_kinds.kind(f) is file_kinds.IMAGE]
    return session.render(title, markdown.render(_plain("\n".join(doc.extra or []))), images)


def card_images(name: str) -> tuple[bytes, bytes]:
    """The card's collage and its thumbnail, as WebP; collage.Unavailable without Chromium."""
    if name not in _card_names():
        raise store.NotFound(name)
    with collage.Session() as session:
        return _card_images(session, name)


def card_file(rel: str) -> bytes:
    """`<stem>.webp` or `<stem>-thumb.webp` of a card, as named in the page."""
    thumb = rel.endswith("-thumb.webp")
    stem = rel.removesuffix("-thumb.webp") if thumb else rel.removesuffix(".webp")
    if stem == rel:
        raise store.NotFound(rel)
    return card_images(f"{stem}.txt")[1 if thumb else 0]


def assets() -> dict[str, bytes]:
    """Every card's collage and thumbnail, by their path beside the page. Where
    collages can't be rendered this raises, so the export writes nothing rather
    than a page without its cards."""
    out = {}
    with collage.Session() as session:
        for name in _card_names():
            page, thumb = _card_images(session, name)
            page_path, thumb_path = _card_paths(name)
            out[page_path], out[thumb_path] = page, thumb
    return out


def render() -> str:
    """The page as HTML."""
    name = _note()
    if name is None:
        raise store.ValidationError(f"no note is tagged {TAG}")
    item = store.get(name)
    template = _template(item)
    if template is None:
        raise store.ValidationError("the portfolio note names no template")
    doc = dsl.parse(store.SCHEMA, item["text"])
    entries = store._INDEX.refresh()
    try:
        page = _env.from_string(files.read_text(template)).render(
            title=re.sub(r"^#+\s*", "", doc.heading),
            body=Markup(markdown.render("\n".join(doc.body))),
            data=doc.data or {},
            cards=[_card(n, entries[n].heading) for n in _card_names()],
        )
    except jinja2.TemplateError as e:
        raise store.ValidationError(f"template: {e}") from e
    return f"{MARKER}\n{page}"


def export_definition() -> exports.Export:
    return exports.Export("portfolio", ".html", "index.html", MARKER, render, assets, CARDS_DIR)
