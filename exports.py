"""Files the app derives from the items and writes to paths set in Settings
(the .bib file, the portfolio page): one runner for all of them, debounced
after writes, at startup and periodically."""

import threading
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import store

DEBOUNCE = 5  # seconds after the last change
INTERVAL = 15 * 60  # full resync, picks up edits made outside the app


@dataclass(frozen=True)
class Export:
    # its config key and settings field
    key: str
    suffix: str
    # appended to a directory given as path
    default_name: str
    # what a file this export wrote starts with; any other file is never overwritten
    marker: str
    render: Callable[[], str]


EXPORTS: dict[str, Export] = {}

# key -> path -> error message, or None if the last sync succeeded
status: dict[str, dict[str, str | None]] = {}
_lock = threading.Lock()
_timer: threading.Timer | None = None


def register(export: Export) -> None:
    EXPORTS[export.key] = export


def paths(key: str) -> list[dict]:
    """The export's paths, each with its last result."""
    return [{"path": p, "error": status.get(key, {}).get(p)} for p in store.get_export_paths(key)]


def set_paths(key: str, value) -> list[str]:
    if key not in EXPORTS:
        raise store.ValidationError(f"unknown export '{key}'")
    return store.set_export_paths(key, value, EXPORTS[key].default_name)


def _write(export: Export, path: str, text: str) -> None:
    p = Path(path)
    if not p.is_absolute():
        raise ValueError("not an absolute path")
    if p.suffix != export.suffix:
        raise ValueError(f"must end in {export.suffix}")
    if not p.parent.is_dir():
        raise ValueError(f"{p.parent} does not exist")
    try:
        current = p.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = None
    if current == text:
        return
    if current and not current.startswith(export.marker):
        raise ValueError("file exists and was not generated by this app")
    tmp = p.with_name(f".{p.name}.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(p)


def _sync(export: Export) -> dict[str, str | None]:
    targets = store.get_export_paths(export.key)
    if not targets:
        return {}
    try:
        text = export.render()
    except Exception as e:  # noqa: BLE001 - report instead of crashing the thread
        return {p: str(e) for p in targets}
    result = {}
    for p in targets:
        try:
            _write(export, p, text)
            result[p] = None
        except (OSError, ValueError) as e:
            result[p] = str(e)
    return result


def sync(key: str | None = None) -> None:
    """Writes the configured files of `key` (all exports when None). Unchanged files are not touched."""
    with _lock:
        for export in EXPORTS.values():
            if key in (None, export.key):
                status[export.key] = _sync(export)


def schedule() -> None:
    """Debounced sync: runs DEBOUNCE seconds after the last call."""
    global _timer
    if _timer:
        _timer.cancel()
    _timer = threading.Timer(DEBOUNCE, sync)
    _timer.daemon = True
    _timer.start()


def start() -> None:
    """Sync now, then periodically in a daemon thread."""
    def loop():
        while True:
            sync()
            time.sleep(INTERVAL)

    threading.Thread(target=loop, daemon=True).start()
